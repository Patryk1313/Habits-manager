export type HabitIconName = keyof typeof HABIT_ICONS;

export const HABIT_ICON_NAMES = Object.keys(
  HABIT_ICONS
) as HabitIconName[];

export function isHabitIconName(
  value: string
): value is HabitIconName {
  return Object.prototype.hasOwnProperty.call(
    HABIT_ICONS,
    value
  );
}

type Props = {
  name: HabitIconName | string | LegacyHabitIcon;
  size?: number;
  color: string;
  strokeWidth?: number;
};

export default function HabitIcon({
  name,
  size = 24,
  color,
  strokeWidth = 2,
}: Props) {
  const value =
    typeof name === "string"
      ? name
      : name.icon;

  if (isHabitIconName(value)) {
    const Icon = HABIT_ICONS[value];
    return (
      <Icon
        size={size}
        color={color}
        strokeWidth={strokeWidth}
      />
    );
  }

  if (typeof value === "string" && value.trim()) {
    return (
      <Text
        style={{
          color,
          fontSize: size,
          lineHeight: size + 4,
          textAlign: "center",
        }}
      >
        {value}
      </Text>
    );
  }

  return (
    <CircleCheck
      size={size}
      color={color}
      strokeWidth={strokeWidth}
    />
  );
}